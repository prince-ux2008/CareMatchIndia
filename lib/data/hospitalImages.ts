export function getHospitalImage(hospitalId: string, hospitalType?: string): string {
  if (HOSPITAL_IMAGES[hospitalId]) {
    return HOSPITAL_IMAGES[hospitalId];
  }
  // Deterministic fallback based on hospitalId string hash
  let hash = 0;
  for (let i = 0; i < hospitalId.length; i++) {
    hash = (hash << 5) - hash + hospitalId.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % DEFAULT_HOSPITAL_IMAGES.length;
  return DEFAULT_HOSPITAL_IMAGES[index];
}
